export const getDifficultyColor = (difficulty) => {
  switch (difficulty) {
    case "Easy": return "#4caf50";
    case "Moderate": return "#ff9800";
    case "Hard": return "#f44336";
    default: return "#9e9e9e";
  }
};

export const getWateringStatus = (lastWatered, intervalDays) => {
  if (!lastWatered) return { status: "unknown", daysUntil: null, label: "Never watered", color: "#9e9e9e" };

  const last = new Date(lastWatered);
  const now = new Date();
  const nextWatering = new Date(last);
  nextWatering.setDate(nextWatering.getDate() + intervalDays);

  const diffMs = nextWatering - now;
  const daysUntil = Math.ceil(diffMs / (1000 * 60 * 60 * 24));

  if (daysUntil < 0) {
    return { status: "overdue", daysUntil, label: `${Math.abs(daysUntil)}d overdue`, color: "#f44336" };
  } else if (daysUntil === 0) {
    return { status: "today", daysUntil, label: "Water today!", color: "#ff9800" };
  } else if (daysUntil <= 2) {
    return { status: "soon", daysUntil, label: `In ${daysUntil}d`, color: "#ff9800" };
  } else {
    return { status: "ok", daysUntil, label: `In ${daysUntil}d`, color: "#4caf50" };
  }
};
